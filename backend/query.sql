-- Объединённый SQL-скрипт для SQLite.
-- Исходные запросы сохранены без изменений.
-- ВНИМАНИЕ: раздел «Пользователи» удаляет существующую таблицу пользователей.
-- При повторном запуске примеры в остальных таблицах добавляются заново.


-- ==================================================
-- Инициативы
-- ==================================================
CREATE TABLE IF NOT EXISTS "Инициативы" (
    "Номер инициативы" INTEGER PRIMARY KEY AUTOINCREMENT,
    "Кто предложил инициативу" TEXT NOT NULL,
    "Инициатива" TEXT NOT NULL
);

