    "Кто предложил инициативу",
    "Инициатива"
)
VALUES (
    'Иванов Иван Иванович',
    'Организовать раздельный сбор отходов.'
);

-- 3. Просмотр всех инициатив
SELECT
    "Номер инициативы",
    "Кто предложил инициативу",
    "Инициатива"
FROM "Инициативы"
ORDER BY "Номер инициативы";


-- ==================================================
-- Пользователи
-- ==================================================
-- Удаление таблицы при необходимости повторного создания
DROP TABLE IF EXISTS "Пользователи";

-- Создание таблицы пользователей
CREATE TABLE "Пользователи" (
    "Имя пользователя" TEXT NOT NULL,

    -- ID хранится как текст, чтобы сохранить ровно 11 цифр
    "ID пользователя" TEXT NOT NULL UNIQUE,

    "Возраст" INTEGER NOT NULL,

    -- ID должен состоять ровно из 11 цифр
    CHECK (
        length("ID пользователя") = 11
        AND "ID пользователя" NOT GLOB '*[^0-9]*'
    ),

    -- Допустимый возраст
    CHECK ("Возраст" BETWEEN 0 AND 150)
);

-- Добавление пользователей.
-- ID генерируется случайно и состоит из 11 цифр.
-- UNIQUE не позволяет повторять уже существующий ID.
INSERT INTO "Пользователи" (
    "Имя пользователя",
    "ID пользователя",
    "Возраст"
)
SELECT
    'Иван Иванов',
    printf('%011d', abs(random()) % 100000000000),
    25
WHERE NOT EXISTS (
    SELECT 1
    FROM "Пользователи"
    WHERE "ID пользователя" =
          printf('%011d', abs(random()) % 100000000000)
);

INSERT INTO "Пользователи" (
    "Имя пользователя",
    "ID пользователя",
    "Возраст"
)
SELECT
    'Анна Петрова',
    printf('%011d', abs(random()) % 100000000000),
    30
WHERE NOT EXISTS (
    SELECT 1
    FROM "Пользователи"
    WHERE "ID пользователя" =
          printf('%011d', abs(random()) % 100000000000)
);

-- Просмотр всех пользователей
SELECT
    "Имя пользователя",
    "ID пользователя",
    "Возраст"
FROM "Пользователи"
ORDER BY "Имя пользователя";


